def build_client_number(name: str, position: int) -> str:
    cleaned = re.sub(r"[^A-Z0-9]", "", name.upper())
    if not cleaned:
        cleaned = f"CLIENT{position:04d}"
    return (cleaned[:10] or f"CLIENT{position:04d}") + f"-{position:03d}"


class Command(BaseCommand):
    help = "Charge les clients historiques fournis par ACS dans la base de données"

    def handle(self, *args, **options):
        creates = 0
        updates = 0

        for index, raw_name in enumerate(LEGACY_CLIENTS, start=1):
            name = raw_name.strip()
            if not name:
                continue

            defaults = {
                "type": "ENTREPRISE",
                "numero_client": build_client_number(name, index),
            }

            client, created = Client.objects.get_or_create(nom=name, defaults=defaults)

            if created:
                creates += 1
                continue

            updated = False
            if not client.numero_client:
                client.numero_client = build_client_number(name, index)
                updated = True
            if client.type != "PARTICULIER" and client.type != "ENTREPRISE":
                client.type = "ENTREPRISE"
                updated = True

            if updated:
                client.save(update_fields=["numero_client", "type", "modifie_le"])
                updates += 1

        self.stdout.write(self.style.SUCCESS(
            f"Import terminé : {creates} clients créés, {updates} clients mis à jour."
        ))

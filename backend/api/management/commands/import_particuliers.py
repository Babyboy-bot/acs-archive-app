def build_code(name: str, index: int) -> str:
    cleaned = re.sub(r"[^A-Z0-9]", "", name.upper())
    if not cleaned:
        cleaned = f"CLIENT{index:04d}"
    return (cleaned[:12] or f"CLIENT{index:04d}") + f"-P{index:04d}"


class Command(BaseCommand):
    help = "Importe la liste fournie de clients particuliers directement dans la base"

    def handle(self, *args, **options):
        created = 0
        updated = 0

        for position, raw_name in enumerate(PARTICULIERS, start=1):
            name = raw_name.strip()
            if not name:
                continue

            defaults = {
                "type": "PARTICULIER",
                "numero_client": build_code(name, position),
            }

            client, was_created = Client.objects.get_or_create(nom=name, defaults=defaults)

            if was_created:
                created += 1
                continue

            changes = []
            if not client.numero_client:
                client.numero_client = build_code(name, position)
                changes.append("numero_client")

            if client.type != "PARTICULIER":
                client.type = "PARTICULIER"
                if "type" not in changes:
                    changes.append("type")

            if changes:
                client.save(update_fields=[*changes, "modifie_le"])
                updated += 1

        self.stdout.write(self.style.SUCCESS(
            f"Import particuliers terminé : {created} créés, {updated} mis à jour."
        ))
